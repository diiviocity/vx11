// Generate the text-library raw API from installed headers. No Python.
module main

import json2
import os

struct TextType {
	name string @[json: 'qualType']
}

struct TextNode {
	kind     string
	name     string
	typ      TextType @[json: 'type']
	variadic bool
	inner    []TextNode
}

fn text_snake(s string) string {
	mut out := ''
	for i, c in s.bytes() {
		if c >= `A` && c <= `Z` {
			if i > 0 && ((s[i - 1] >= `a` && s[i - 1] <= `z`) || (i + 1 < s.len && s[i + 1] >= `a` && s[i + 1] <= `z`)) {
				out += '_'
			}
			out += (c + 32).ascii_str()
		} else {
			out += c.ascii_str()
		}
	}
	return out
}

fn text_type(raw string, module_name string) !string {
	t := raw.replace('const ', '').trim_space()
	if t == 'void *' { return 'voidptr' }
	if t.ends_with('*') { return '&' + text_type(t[..t.len - 1].trim_space(), module_name)! }
	base := {
		'void':           ''
		'void *':         'voidptr'
		'char':           'char'
		'unsigned char':  'u8'
		'unsigned short': 'u16'
		'unsigned int':   'u32'
		'int':            'i32'
		'double':         'f64'
		'FcChar8':        'u8'
		'FcChar16':       'u16'
		'FcChar32':       'u32'
		'FcBool':         'i32'
		'FT_UInt':        'u32'
		'FT_Face':        'voidptr'
	}
	if t == 'void' && raw.ends_with('*') { return 'voidptr' }
	if t in base { return base[t] }
	if t in ['Display', 'Visual', 'Colormap', 'Drawable', 'Pixmap', 'Region', 'XRectangle'] {
		return 'vx11.' + t
	}
	if t.starts_with('Fc') { return if module_name == 'xft' { 'fontconfig.' + t } else { t } }
	if t.starts_with('Xft') || t in ['XRenderColor', 'XGlyphInfo', 'Picture'] { return t }
	return error('unsupported text ABI type: ' + raw)
}

fn main() {
	generate_text() or {
		eprintln(err)
		exit(1)
	}
}

fn generate_text() ! {
	root := os.dir(os.dir(@FILE))
	tmp := os.join_path(os.temp_dir(), 'vx11-textgen-${os.getpid()}')
	os.mkdir_all(tmp)!
	defer { os.rmdir_all(tmp) or {} }
	flags := os.exec(['pkg-config', '--cflags', 'xft', 'fontconfig'])
	if flags.exit_code != 0 { return error(flags.output) }
	path := os.join_path(tmp, 'text.h')
	os.write_file(path, '#include <X11/Xft/Xft.h>\n')!
	clang := if os.getenv('CLANG') == '' { 'clang' } else { os.getenv('CLANG') }
	mut argv := [clang, '-Xclang', '-ast-dump=json', '-fsyntax-only']
	argv << flags.output.fields()
	argv << path
	result := os.exec(argv)
	if result.exit_code != 0 { return error(result.output) }
	ast := json2.decode[TextNode](result.output)!
	fc_names := 'FcInit FcGetVersion FcNameParse FcNameUnparse FcStrFree FcPatternCreate FcPatternDuplicate FcPatternReference FcPatternDestroy FcPatternDel FcPatternAddInteger FcPatternAddDouble FcPatternAddString FcPatternAddBool FcPatternAddCharSet FcPatternGetInteger FcPatternGetDouble FcPatternGetString FcPatternGetBool FcPatternGetCharSet FcConfigSubstitute FcDefaultSubstitute FcFontMatch FcFontSetMatch FcFontSort FcFontSetSort FcFontRenderPrepare FcFontSetCreate FcFontSetAdd FcFontSetDestroy FcFontSetSortDestroy FcCharSetCreate FcCharSetCopy FcCharSetDestroy FcCharSetAddChar FcCharSetDelChar FcCharSetHasChar FcCharSetCount FcCharSetEqual FcCharSetUnion FcCharSetIntersect FcCharSetSubtract FcCharSetIsSubset FcFontList FcObjectSetCreate FcObjectSetAdd FcObjectSetDestroy FcConfigGetCurrent FcConfigReference FcConfigDestroy'.split(' ')
	for module_name in ['fontconfig', 'xft'] {
		mut out := '// Generated by tools/generate_text.v. Do not edit.\nmodule ${module_name}\n\n'
		if module_name == 'xft' { out += 'import vx11\nimport vx11.fontconfig\n\n' }
		mut bridge := '/* Generated enum-output adapters. */\n#include <X11/Xft/Xft.h>\n'
		mut manifest := map[string]string{}
		for n in ast.inner {
			if n.kind != 'FunctionDecl' || n.variadic { continue }
			if module_name == 'fontconfig' && n.name !in fc_names { continue }
			if module_name == 'xft' && !n.name.starts_with('Xft') { continue }
			prefix := if module_name == 'xft' { 3 } else { 2 }
			short_name := text_snake(n.name[prefix..])
			name := if short_name == 'init' { module_name + '_init' } else { short_name }
			ps := n.inner.filter(it.kind == 'ParmVarDecl')
			mut params := []string{}
			mut args := []string{}
			mut cparams := []string{}
			mut cargs := []string{}
			mut locals := ''
			mut outputs := ''
			for i, p in ps {
				t := p.typ.name
				vt := if t == 'void *' { 'voidptr' } else { text_type(t, module_name)! }
				params << 'arg${i} ${vt}'
				args << 'arg${i}'
				if t == 'FcResult *' {
					cparams << 'int *arg${i}'
					locals += ' FcResult value${i}=FcResultNoMatch;\n'
					cargs << '&value${i}'
					outputs += ' if(arg${i}) *arg${i}=(int)value${i};\n'
				} else {
					cparams << '${t} arg${i}'
					cargs << 'arg${i}'
				}
			}
			c_ret := n.typ.name.all_before('(').trim_space()
			ret := if c_ret == 'void *' { 'voidptr' } else { text_type(c_ret, module_name)! }
			suffix := if ret == '' { '' } else { ' ' + ret }
			c_name := if locals == '' { n.name } else { 'vx11_' + n.name }
			if locals != '' {
				bridge += 'static inline ${c_ret} ${c_name}(${cparams.join(', ')}) {\n${locals} ${c_ret} result=${n.name}(${cargs.join(', ')});\n${outputs} return result;\n}\n'
			}
			out += 'fn C.${c_name}(${params.join(', ')})${suffix}\n\n// ${n.name}: ownership and return codes follow the C library.\npub fn ${name}(${params.join(', ')})${suffix} {\n\t' + (if ret == '' {
				''
			} else {
				'return '
			}) + 'C.${c_name}(${args.join(', ')})\n}\n\n'
			manifest[n.name] = name
		}
		os.write_file(os.join_path(root, module_name, 'raw.c.v'), out)!
		// Fontconfig alone must not depend on the Xft/FreeType development headers.
		if module_name == 'fontconfig' {
			bridge = bridge.replace('#include <X11/Xft/Xft.h>', '#include <fontconfig/fontconfig.h>')
		}
		os.write_file(os.join_path(root, module_name, 'bridge.h'), bridge)!
		os.write_file(os.join_path(root, module_name, 'api.json'), json2.encode(manifest,
			prettify: true
		) + '\n')!
		println('${module_name}: ${manifest.len} raw calls')
	}
}
