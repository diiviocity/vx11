// Regenerate from installed Unix X11 headers. Requires clang and a C compiler.
module main

import json2
import os

struct CType {
	qual_type string @[json: 'qualType']
}

struct Location {
	file   string
	offset int
}

struct Ref {
	id string
}

struct Node {
	id       string
	kind     string
	name     string
	typ      CType @[json: 'type']
	loc      Location
	decl     Ref
	tag      string @[json: 'tagUsed']
	value    string
	variadic bool
	inner    []Node
}

struct Manifest {
	headers   []string
	functions map[string]string
	constants map[string]string
}

struct Generator {
mut:
	typedefs map[string]Node
	records  map[string]Node
	tags     map[string]string
	by_id    map[string]Node
	types    []string
	bridge   []string
	sources  map[string]string
}

const headers = ['Xlib.h', 'Xutil.h', 'Xresource.h', 'Xatom.h', 'keysym.h', 'cursorfont.h', 'XKBlib.h']
const keywords = ['as', 'asm', 'assert', 'atomic', 'bool', 'break', 'const', 'continue', 'defer',
	'else', 'enum', 'false', 'fn', 'for', 'go', 'goto', 'if', 'import', 'in', 'interface', 'is',
	'lock', 'match', 'module', 'mut', 'none', 'or', 'pub', 'return', 'rlock', 'select', 'shared',
	'sizeof', 'static', 'struct', 'true', 'type', 'typeof', 'union', 'unsafe', 'volatile', '__global']
const prelude = '// Generated by tools/generate.v. Do not edit.\nmodule vx11\n\n'

fn ident(s string) string {
	if s in ['string', 'map', 'c'] { return s + '_arg' }
	return if s in keywords { '@' + s } else { s }
}

fn snake(s string) string {
	mut out := ''
	for i, c in s.bytes() {
		if c >= `A` && c <= `Z` {
			if i > 0 && s[i - 1] != `_` && ((s[i - 1] >= `a` && s[i - 1] <= `z`) || (s[i - 1] >= `0` && s[i - 1] <= `9`) || (i + 1 < s.len && s[i + 1] >= `a` && s[i + 1] <= `z`)) {
				out += '_'
			}
			out += (c + 32).ascii_str()
		} else {
			out += c.ascii_str()
		}
	}
	return out
}

fn split_args(s string) []string {
	mut result := []string{}
	mut start := 0
	mut depth := 0
	for i, c in s.bytes() {
		if c == `(` || c == `[` { depth++ }
		if c == `)` || c == `]` { depth-- }
		if c == `,` && depth == 0 {
			result << s[start..i].trim_space()
			start = i + 1
		}
	}
	if s[start..].trim_space() != '' { result << s[start..].trim_space() }
	return result
}

fn numeric_expression(s string, known map[string]string) bool {
	mut token := ''
	mut tokens := []string{}
	for c in s.bytes() {
		if c.is_alnum() || c == `_` {
			token += c.ascii_str()
		} else {
			if token != '' {
				tokens << token
				token = ''
			}
			if c !in ' \t()<>|&~+-*/%^!=?:'.bytes() { return false }
		}
	}
	if token != '' { tokens << token }
	if tokens.len == 0 { return false }
	mut has_value := false
	for t in tokens {
		if t[0].is_digit() {
			has_value = true
			continue
		}
		if t in ['unsigned', 'long', 'int', 'short', 'Atom', 'KeySym'] { continue }
		if t !in known || known[t].starts_with('"') { return false }
		has_value = true
	}
	return has_value
}

fn (mut g Generator) index(n Node) {
	if n.id != '' { g.by_id[n.id] = n }
	for c in n.inner { g.index(c) }
}

fn record_ref(n Node) string {
	if n.decl.id != '' { return n.decl.id }
	for c in n.inner {
		r := record_ref(c)
		if r != '' { return r }
	}
	return ''
}

fn (g &Generator) typ(raw string) !string {
	t := raw.replace('const ', '').replace('volatile ', '').replace('restrict ', '').trim_space()
	if t.contains('(*)(') {
		parts := t.split_nth('(*)(', 2)
		ret := g.typ(parts[0])!
		args := parts[1].trim_right(')')
		mut params := []string{}
		if args != '' && args != 'void' {
			for a in split_args(args) { params << g.typ(a)! }
		}
		return 'fn (' + params.join(', ') + ')' + if ret == '' { '' } else { ' ' + ret }
	}
	if t.ends_with(']') {
		at := t.last_index('[') or { return error('bad array ' + t) }
		len := t[at + 1..t.len - 1]
		return (if len == '' { '&' } else { '[' + len + ']' }) + g.typ(t[..at])!
	}
	if t.ends_with('*') {
		b := t[..t.len - 1].trim_space()
		if b == 'void' { return 'voidptr' }
		if (b.starts_with('struct ') || b.starts_with('union ')) && b !in g.tags {
			return 'voidptr'
		}
		return '&' + g.typ(b)!
	}
	base := {
		'void':               ''
		'char':               'char'
		'signed char':        'i8'
		'unsigned char':      'u8'
		'short':              'i16'
		'unsigned short':     'u16'
		'int':                'i32'
		'unsigned int':       'u32'
		'long':               'CLong'
		'unsigned long':      'CULong'
		'long long':          'i64'
		'unsigned long long': 'u64'
		'float':              'f32'
		'double':             'f64'
		'wchar_t':            'i32'
		'size_t':             'CULong'
	}
	if t in base { return base[t] }
	if t in g.tags { return g.tags[t] }
	if t.starts_with('enum ') { return 'i32' }
	if t in g.typedefs { return t }
	return error('unsupported C type: ' + t)
}

fn (mut g Generator) record(name string, n Node) ! {
	mut fields := []string{}
	mut nested := n.inner.filter(it.kind == 'RecordDecl')
	for f in n.inner {
		if f.kind != 'FieldDecl' { continue }
		ft := f.typ.qual_type
		mut vt := ''
		if ft !in g.tags && (ft.contains('(unnamed ') || ft.contains('(anonymous ') || nested.any(ft == it.tag + ' ' + it.name)) {
			if nested.len == 0 { return error('unresolved nested record ' + name + '.' + f.name) }
			child := nested[0]
			nested.delete(0)
			childname := name + '_' + f.name
			g.bridge << 'typedef __typeof__(((${name} *)0)->${f.name}) ${childname};\n'
			g.record(childname, child)!
			g.tags[ft] = childname
			vt = childname
		} else {
			vt = g.typ(ft)!
		}
		field_name := if f.name in keywords { '@' + f.name } else { f.name }
		fields << '\t${field_name} ${vt}\n'
	}
	tag := if n.tag == '' { 'struct' } else { n.tag }
	g.types << '@[typedef]\npub ${tag} C.${name} {\n'
	if fields.len > 0 { g.types << 'pub mut:\n' + fields.join('') }
	g.types << '}\n\npub type ${name} = C.${name}\n\n'
}

fn run(cmd []string) !string {
	r := os.exec(cmd)
	if r.exit_code != 0 { return error('${cmd}\n${r.output}') }
	return r.output
}

fn main() {
	generate() or {
		eprintln(err)
		exit(1)
	}
}

fn generate() ! {
	root := os.dir(os.dir(@FILE))
	clang := if os.getenv('CLANG') == '' { 'clang' } else { os.getenv('CLANG') }
	tmp := os.join_path(os.temp_dir(), 'vx11-generate-${os.getpid()}')
	os.mkdir_all(tmp)!
	defer { os.rmdir_all(tmp) or {} }
	path := os.join_path(tmp, 'headers.h')
	source := headers.map('#include <X11/${it}>\n').join('')
	os.write_file(path, source)!
	ast_text := run([clang, '-Xclang', '-ast-dump=json', '-fsyntax-only', path])!
	ast := json2.decode[Node](ast_text)!
	macros := run([clang, '-E', '-dM', path])!
	mut nodes := []Node{}
	mut file := ''
	mut g := Generator{}
	for n in ast.inner {
		g.index(n)
		if n.loc.file != '' { file = n.loc.file }
		if file.contains('/X11/') {
			nodes << n
			g.sources[n.id] = file
		}
	}
	for n in nodes {
		if n.kind == 'TypedefDecl' && !n.name.starts_with('_') { g.typedefs[n.name] = n }
	}
	for name, n in g.typedefs {
		t := n.typ.qual_type
		if (t.starts_with('struct ') || t.starts_with('union ')) && !t.contains('*') {
			g.records[name] = g.by_id[record_ref(n)]
			g.tags[t] = name
		}
	}
	g.types << prelude
	g.types << 'pub type AfterFunction = fn (&Display) i32\n\n'
	g.bridge << '/* Generated by tools/generate.v. */\n#ifndef VX11_BRIDGE_H\n#define VX11_BRIDGE_H\n' + source
	mut callbacks := map[string]bool{}
	for name, n in g.typedefs {
		if name in g.records {
			g.record(name, g.records[name])!
		} else {
			if n.typ.qual_type.contains('(*)(') {
				callbacks[name] = true
			}
			g.types << 'pub type ${name} = ${g.typ(n.typ.qual_type)!}\n\n'
		}
	}
	os.write_file(os.join_path(root, 'types.c.v'), g.types.join(''))!
	mut functions := [prelude]
	mut methods := [prelude]
	custom_methods := ['flush', 'sync', 'pending', 'next_event', 'close', 'close_display', 'raw',
		'color', 'black_pixel', 'white_pixel']
	mut fmap := map[string]string{}
	for n in nodes {
		cn := n.name
		if n.kind != 'FunctionDecl' || !cn.starts_with('X') || cn in fmap { continue }
		vn := if cn.starts_with('Xrm') || cn.starts_with('Xkb') {
			snake(cn)
		} else {
			snake(cn[1..])
		}
		ps := n.inner.filter(it.kind == 'ParmVarDecl')
		mut params := []string{}
		mut argv := []string{}
		mut c_params := []string{}
		mut c_args := []string{}
		mut bridge_params := []string{}
		mut bridge_args := []string{}
		mut has_callback := false
		mut method_params := []string{}
		mut method_args := ['c.raw()!']
		mut checks := []string{}
		header := os.read_file(g.sources[n.id])!
		for i, p in ps {
			mut pname := p.name.trim_left('_')
			if pname == '' && p.loc.offset > n.loc.offset && p.loc.offset <= header.len {
				fragment := header[n.loc.offset..p.loc.offset]
				if fragment.contains('/*') && fragment.all_after_last('/*').contains('*/') {
					comment := fragment.all_after_last('/*').all_before('*/').trim_space()
					if comment != '' && comment.bytes().all(it.is_alnum() || it == `_`) {
						pname = comment
					}
				}
			}
			mut pn := ident(if pname == '' { 'arg${i}' } else { snake(pname) })
			if pn in argv { pn = 'arg${i}' }
			param_type := g.typ(p.typ.qual_type)!
			params << pn + ' ' + param_type
			argv << pn
			is_callback := param_type in callbacks || param_type.starts_with('fn ')
			has_callback = has_callback || is_callback
			c_params << pn + ' ' + (if is_callback { 'voidptr' } else { param_type })
			c_args << if is_callback { 'voidptr(${pn})' } else { pn }
			bridge_params << (if is_callback { 'void *' } else { p.typ.qual_type }) + ' a${i}'
			bridge_args << if is_callback { '(${p.typ.qual_type})a${i}' } else { 'a${i}' }
			if i > 0 {
				if p.typ.qual_type == 'const char *' {
					method_params << pn + ' string'
					method_args << '&char(${pn}.str)'
					checks << "\tif ${pn}.contains('\\x00') { return error('${pn} contains NUL') }\n"
				} else {
					method_params << params.last()
					method_args << pn
				}
			}
		}
		ret := if cn in ['XSynchronize', 'XSetAfterFunction'] {
			'fn (&Display) i32'
		} else {
			g.typ(n.typ.qual_type.all_before('(').trim_space())!
		}
		sig := params.join(', ')
		call := argv.join(', ')
		suffix := if ret == '' { '' } else { ' ' + ret }
		if n.variadic {
			mut cs := []string{}
			for i, p in ps { cs << p.typ.qual_type + ' a${i}' }
			cr := n.typ.qual_type.all_before('(').trim_space()
			g.bridge << 'static inline ${cr} vx11_${cn}(${cs.join(', ')}, void **args, int count) {\n switch(count) {\n'
			for count := 0; count <= 32; count += 2 {
				mut ca := []string{}
				for i in 0 .. ps.len { ca << 'a${i}' }
				for i in 0 .. count { ca << 'args[${i}]' }
				ca << '(void *)0'
				g.bridge << ' case ${count}: return ${cn}(${ca.join(', ')});\n'
			}
			g.bridge << ' default: return 0;\n }\n}\n'
			functions << 'fn C.vx11_${cn}(${sig}, args &voidptr, count i32)${suffix}\n\n'
			functions << '// ${cn}: alternating name/value pointers, without a trailing null.\npub fn ${vn}(${sig}, args []voidptr) !${ret} {\n'
			functions << "\tif args.len % 2 != 0 || args.len > 32 { return error('expected at most 16 name/value pairs') }\n"
			functions << '\treturn C.vx11_${cn}(${call}, args.data, i32(args.len))\n}\n\n'
		} else {
			callback_return := ret in callbacks || ret.starts_with('fn ')
			// POSIX callback pointers cross a void* adapter so the C compiler,
			// rather than V's const inference, controls the callback prototype.
			needs_bridge := has_callback || callback_return
			c_name := if needs_bridge { 'vx11_' + cn } else { cn }
			if needs_bridge {
				c_ret := if callback_return {
					'void *'
				} else {
					n.typ.qual_type.all_before('(').trim_space()
				}
				g.bridge << 'static inline ${c_ret} ${c_name}(${bridge_params.join(', ')}) {\n'
				g.bridge << (if ret == '' { ' ' } else { ' return ' }) + (if callback_return {
					'(void *)'
				} else {
					''
				}) + '${cn}(${bridge_args.join(', ')});\n}\n'
			}
			c_suffix := if callback_return { ' voidptr' } else { suffix }
			c_call := 'C.${c_name}(${c_args.join(', ')})'
			cast_name := if ret.starts_with('fn ') { 'AfterFunction' } else { ret }
			call_expression := if callback_return { '${cast_name}(${c_call})' } else { c_call }
			functions << 'fn C.${c_name}(${c_params.join(', ')})${c_suffix}\n\n// ${cn}: raw Xlib ownership and return codes.\npub fn ${vn}(${sig})${suffix} {\n\t' + if ret == '' {
				''
			} else {
				'return '
			} + '${call_expression}\n}\n\n'
		}
		if !n.variadic && ps.len > 0 && ps[0].typ.qual_type == 'Display *' && vn !in custom_methods && !ret.starts_with('fn ') {
			methods << '// ${cn}, borrowing this connection. Other ownership follows the raw call.\n'
			methods << 'pub fn (c &Connection) ${vn}(${method_params.join(', ')}) !${ret} {\n'
			methods << checks.join('')
			methods << '\t' + (if ret == '' { '' } else { 'return ' }) + '${vn}(${method_args.join(', ')})\n}\n\n'
		}
		fmap[cn] = vn
	}
	os.write_file(os.join_path(root, 'functions.c.v'), functions.join(''))!
	os.write_file(os.join_path(root, 'methods.v'), methods.join(''))!
	// Read names only from public headers; let the C compiler evaluate macros.
	mut names := map[string]bool{}
	for h in ['X.h', 'Xlib.h', 'Xutil.h', 'Xresource.h', 'Xatom.h', 'keysymdef.h', 'cursorfont.h',
		'extensions/XKB.h'] {
		os.write_file(path, '#include <X11/${h}>\n')!
		search := run([clang, '-E', '-H', path])!
		hp := search.split_into_lines().filter(it.starts_with('. ') && it.ends_with('/' + h))
		if hp.len != 1 { return error('cannot locate ' + h) }
		text := os.read_file(hp[0][2..])!
		for line in text.split_into_lines() {
			l := line.trim_space()
			if !l.starts_with('#') { continue }
			words := l[1..].trim_space().fields()
			if words.len == 0 || words[0] != 'define' { continue }
			if words.len >= 3 && !words[1].contains('(') && !words[1].starts_with('_') {
				names[words[1]] = true
			}
		}
	}
	mut defs := map[string]string{}
	for line in macros.split_into_lines() {
		words := line.fields()
		if words.len >= 3 && words[1] in names { defs[words[1]] = words[2..].join(' ') }
	}
	mut candidates := map[string]string{}
	for k, v in defs {
		if (v.starts_with('"') && v.ends_with('"')) || v.starts_with('((Atom)') || v.bytes().all(it in '0123456789abcdefABCDEFxXULul()<>|&~+- \t'.bytes()) {
			candidates[k] = v
		}
	}
	for {
		mut added := false
		for k, v in defs {
			if k !in candidates && (v in candidates || numeric_expression(v, candidates)) {
				candidates[k] = if v in candidates { candidates[v] } else { v }
				added = true
			}
		}
		if !added { break }
	}
	mut c := source + '#include <stdio.h>\nint main(void) {\n'
	for k, v in candidates {
		if !v.starts_with('"') { c += 'printf("${k} %lld\\n", (long long)(${k}));\n' }
	}
	c += '}\n'
	cp := os.join_path(tmp, 'constants.c')
	exe := os.join_path(tmp, 'constants')
	os.write_file(cp, c)!
	run([clang, cp, '-o', exe])!
	mut values := map[string]string{}
	for line in (run([exe])!).split_into_lines() {
		words := line.fields()
		if words.len == 2 { values[words[0]] = words[1] }
	}
	mut constants := [prelude]
	mut cmap := map[string]string{}
	mut seen := map[string]bool{}
	mut keys := candidates.keys()
	keys.sort()
	for cn in keys {
		mut vn := snake(cn)
		if cn.starts_with('XK_') {
			tail := cn[3..]
			vn = 'key_' + snake(tail)
			// Preserve case-distinct keysyms with explicit capital markers.
			if keys.any(it != cn && it.starts_with('XK_') && snake(it) == snake(cn)) {
				mut encoded := ''
				for ch in tail.bytes() {
					encoded += if ch >= `A` && ch <= `Z` {
						'capital_' + (ch + 32).ascii_str()
					} else {
						ch.ascii_str()
					}
				}
				vn = 'key_' + encoded
			}
		}
		if vn in keywords || vn in fmap.values() { vn = 'x_' + vn }
		if vn in seen { return error('constant collision: ' + cn + ' -> ' + vn) }
		seen[vn] = true
		v := candidates[cn]
		mut value := if v.starts_with('"') {
			"'" + v[1..v.len - 1].replace("'", "\\'") + "'"
		} else {
			values[cn]
		}
		if !v.starts_with('"') && value.i64() > 2147483647 {
			value = if value.u64() <= 4294967295 { 'u32(${value})' } else { 'u64(${value})' }
		}
		if cn == 'AllPlanes' { value = '~CULong(0)' }
		constants << '// ${cn}\npub const ${vn} = ${value}\n'
		cmap[cn] = vn
	}
	for n in nodes {
		if n.kind != 'EnumDecl' { continue }
		mut value := -1
		for e in n.inner {
			if e.kind != 'EnumConstantDecl' { continue }
			value = if e.inner.len > 0 { e.inner[0].value.int() } else { value + 1 }
			vn := snake(e.name)
			if vn !in seen {
				constants << '// ${e.name}\npub const ${vn} = ${value}\n'
				cmap[e.name] = vn
				seen[vn] = true
			}
		}
	}
	os.write_file(os.join_path(root, 'constants.v'), constants.join(''))!
	g.bridge << '#endif\n'
	os.write_file(os.join_path(root, 'vx11_bridge.h'), g.bridge.join(''))!
	os.write_file(os.join_path(root, 'api.json'), json2.encode(Manifest{headers, fmap, cmap},
		prettify: true
	) + '\n')!
	println('Generated ${fmap.len} functions, ${g.typedefs.len} types, ${cmap.len} constants')
}
